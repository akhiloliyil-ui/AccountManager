// Bundles drizzle-kit's SQL migrations into src/migrations.gen.ts so the app can apply them
// from inside any bundle (Next.js, tests) without locating files on disk at runtime.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const journal = JSON.parse(readFileSync(new URL("drizzle/meta/_journal.json", root), "utf8"));
const migrations = journal.entries.map((e) => ({
  tag: e.tag,
  sql: readFileSync(new URL(`drizzle/${e.tag}.sql`, root), "utf8"),
}));

writeFileSync(
  new URL("src/migrations.gen.ts", root),
  `// Generated by scripts/bundle-migrations.mjs from drizzle/*.sql. Do not edit.\n` +
    `export const migrations: { tag: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Bundled ${migrations.length} migration(s).`);
